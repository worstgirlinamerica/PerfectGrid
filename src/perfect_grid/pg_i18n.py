DEFAULT_LANG = "en"


def get_tr(lang_code: str):
    """Return a translation function for the given language code."""
    strings = LANGUAGES.get(lang_code, LANGUAGES[DEFAULT_LANG])
    fallback = LANGUAGES[DEFAULT_LANG]

    def tr(key: str) -> str:
        return strings.get(key, fallback.get(key, key))

    return tr


def language_display_names() -> list[tuple[str, str]]:
    """Return [(code, display_name), ...] sorted by display name."""
    return sorted(
        [(code, data["name"]) for code, data in LANGUAGES.items()],
        key=lambda x: x[1],
    )
